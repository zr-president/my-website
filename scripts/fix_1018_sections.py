    m = pat.search(d)
    if not m:
        print('  ❌ 未找到:', k); continue
    body = m.group(2)
    # 只替换 summary 的值
    sm = re.search(r'("?summary"?\s*:\s*)"(?:[^"\\]|\\.)*"', body)
    if not sm:
        print('  ⚠️  %s 没有 summary 字段' % k); continue
