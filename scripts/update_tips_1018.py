# ---- 应用 tips ----
i_ins = d.find('var INSIGHTS = {')
i_end = i_ins + re.search(r'\n\};', d[i_ins:]).end()
seg = d[i_ins:i_end]
done, miss = [], []
for key, val in TIPS.items():
    pat = re.compile(r'((?:"' + re.escape(key) + r'"|' + re.escape(key) + r')\s*:\s*\{)([\s\S]*?)(\n  \})')
    m = pat.search(seg)
    if not m:
        miss.append(key + '(段未找到)'); continue
    body = m.group(2)
    tm = re.search(r'("?tip"?\s*:\s*)(?:"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')', body)
    if not tm:
        miss.append(key + '(无tip)'); continue
    nb = body[:tm.start()] + tm.group(1) + json.dumps(val, ensure_ascii=False) + body[tm.end():]
    seg = seg[:m.start()] + m.group(1) + nb + m.group(3) + seg[m.end():]
    done.append(key)

d = d[:i_ins] + seg + d[i_end:]
print('✅ tip 重写：%d/%d 成功' % (len(done), len(TIPS)))
if miss:
    print('⚠️  跳过：%s' % ', '.join(miss))

