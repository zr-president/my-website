# 残留检查
t2 = open('daily_data.js', encoding='utf-8').read()
m = re.search(r'var\s+PICKS\s*=', t2)
i = t2.index('{', m.end())
depth = 0
instr = None
j = i
while j < len(t2):
    c = t2[j]
    if instr:
        if c == '\\':
            j += 2
            continue
        if c == instr:
            instr = None
        j += 1
        continue
    if c in '"\'':
        instr = c
        j += 1
        continue
    if c == '{':
        depth += 1
    elif c == '}':
        depth -= 1
        if depth == 0:
            break
    j += 1
blk = t2[i:j + 1]
