def get_block(text, key):
    """返回 (start, end) —— 覆盖 `key: { ... }` 整个块"""
    m = re.search(r'(?:"' + re.escape(key) + r'"|' + re.escape(key) + r')\s*:\s*\{', text)
    if not m:
        return None, None
    i = text.index('{', m.start())
    depth = 0
    j = i
    in_str = None
    while j < len(text):
        ch = text[j]
        if in_str:
            if ch == '\\':
                j += 2
                continue
            if ch == in_str:
                in_str = None
            j += 1
            continue
        if ch in '"\'':
            in_str = ch
            j += 1
            continue
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return i, j + 1
        j += 1
    return None, None

def set_field(block, field, value):
    """把 block 里的 field: "..." 或 field: '...' 换成 field: "value\""""
    # 键名可能带引号（"summary": {...}）也可能不带（summary: {...}）—— 两种都要匹配
    pat = re.compile(r'((?:"' + re.escape(field) + r'"|' + re.escape(field) + r')\s*:\s*)'
                     r'("(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')')
    newv = json.dumps(value, ensure_ascii=False)
    if not pat.search(block):
        return block, False
    return pat.sub(lambda m: m.group(1) + newv, block, count=1), True

def apply_sections(text, data):
    """data: {key: {summary, trend, tip}}"""
    changed = []
    for key, fields in data.items():
        s, e = get_block(text, key)
        if s is None:
            print('  ⚠️ 找不到分区 ' + key)
            continue
        blk = text[s:e]
        for f, v in fields.items():
            # 统一归一化：把占位符 @D 换成当日日期串（幂等，summary 已换过也不影响）
            v = v.replace('@D', D)
            blk, ok = set_field(blk, f, v)
            if not ok:
                print('  ⚠️ ' + key + ' 缺字段 ' + f)
        text = text[:s] + blk + text[e:]
        changed.append(key)
    return text, changed


