# 只在 var INSIGHTS = { ... } 范围内替换 —— 否则会命中 briefing 里的 "anime": {...} 等卡片
_ins = text.index('var INSIGHTS')
_open = text.index('{', _ins)
_depth = 0
_close = None
_instr = None
_i = _open
while _i < len(text):
    _c = text[_i]
    if _instr:
        if _c == '\\':
            _i += 2
            continue
        if _c == _instr:
            _instr = None
        _i += 1
        continue
    if _c in '"\'':
        _instr = _c
        _i += 1
        continue
    if _c == '{':
        _depth += 1
    elif _c == '}':
        _depth -= 1
        if _depth == 0:
            _close = _i + 1
            break
    _i += 1
assert _close, 'INSIGHTS 未闭合'
print('INSIGHTS 范围：%d - %d' % (_open, _close))

