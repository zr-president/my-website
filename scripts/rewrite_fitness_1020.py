def read_js(text, key):
    for q, esc in [(DQ, r'"(?:[^"\\]|\\.)*"'), (SQ, r"'(?:[^'\\]|\\.)*'")]:
        m = re.search(r'(DETAIL\.' + key + r'\s*=\s*)(' + esc + ')', text)
        if m:
            inner = m.group(2)[1:-1]
            val = (inner.replace('\\\\', '\\').replace('\\' + q, q)
                        .replace('\\n', '\n').replace('\\"', '"').replace("\\'", "'"))
            return m.start(2), m.end(2), val
    return None, None, None


def write_js(text, key, val):
    s, e, _ = read_js(text, key)
    if s is None:
        return text, False
    return text[:s] + json.dumps(val, ensure_ascii=False) + text[e:], True


