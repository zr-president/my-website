def j(o):
    return json.dumps(o, ensure_ascii=False, indent=2).replace('\n', '\n  ')


def set_section(key, obj):
    """整体替换 INSIGHTS.<key> 对象"""
    global d
    obj = dict(obj)
    obj['updated'] = TODAY
    pat = re.compile(r'\n  ' + re.escape(key) + r': \{[\s\S]*?\n  \},')
    m = pat.search(d)
    if not m:
        print('  MISS', key); return
    d = d[:m.start()] + '\n  ' + key + ': ' + j(obj) + ',' + d[m.end():]
    print('  ✅', key)


